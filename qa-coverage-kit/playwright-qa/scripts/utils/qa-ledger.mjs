#!/usr/bin/env node
// qa-ledger — the suite's test-ID checks and generated documentation.
//
// Parses spec files statically (no Playwright config load, no .env) plus qa-output/test-cases.md,
// checks every test ID against the ID scheme, and generates everything derived from the specs.
// It never allocates an ID.
//
// ID scheme (playwright-qa/CLAUDE.md → Identifiers):
//   <TICKET>-<n>        tests numbered within their originating ticket (e.g. PROJ-327-1)
//   MAN-<slug>-<n>      tests from manual-test work with no ticket
//
// Generated outputs:
//   qa-output/test-index.md          one row per test (plus not-automated cases from test-cases.md)
//   qa-output/jira-test-mapping.md   ticket → tests
//   marker blocks <!-- qa-ledger:<name>:start/end --> in CLAUDE.md (header) and README.md (spec-table)
//
// Usage (from playwright-qa/scripts/):
//   npm run qa:ledger                        summary; stale generated output is a warning
//   npm run qa:ledger -- --write             regenerate all generated outputs
//   npm run qa:ledger -- --check             exit 1 if any check fails or generated output is stale
//   npm run qa:ledger -- --json              full report as JSON
//   npm run qa:ledger -- --tickets PROJ-327,PROJ-412   which of these tickets have coverage

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPTS_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const QA_ROOT = join(SCRIPTS_DIR, '..');
const REPO_ROOT = join(QA_ROOT, '..');
const TESTS_DIR = join(SCRIPTS_DIR, 'tests');
const OUTPUT_DIR = join(QA_ROOT, 'qa-output');
const PATHS = {
  testCases: join(OUTPUT_DIR, 'test-cases.md'),
  testIndex: join(OUTPUT_DIR, 'test-index.md'),
  jiraMapping: join(OUTPUT_DIR, 'jira-test-mapping.md'),
  claudeMd: join(QA_ROOT, 'CLAUDE.md'),
  readme: join(QA_ROOT, 'README.md'),
  packageJson: join(SCRIPTS_DIR, 'package.json'),
  workflowToml: join(REPO_ROOT, 'workflow.toml'),
};

const ID_PATTERN = /^(MAN-[a-z0-9]+(?:-[a-z0-9]+)*-\d+|[A-Z][A-Z0-9]+-\d+-\d+)\b/;
const TICKET_TAG_PATTERN = /@([A-Z][A-Z0-9]+-\d+)\b/g;
// test('title' …) / test.skip('title' …) etc. — a string first argument marks a declaration;
// a bare runtime test.skip() inside a body has none and is not matched.
const DECLARATION_PATTERN = /\btest(?:\.(skip|fixme|fail|only))?\(\s*(['"`])((?:\\.|(?!\2).)*)\2/g;
const STATUS_LABEL = { active: 'Active', fail: 'Expected fail', skip: 'Skipped', fixme: 'Fixme', only: 'Only', manual: 'Not automated' };
const GENERATED_BANNER = '> Generated by `npm run qa:ledger -- --write` from the spec files — do not edit by hand.';

function parseArgs(argv) {
  const args = { json: false, write: false, check: false, tickets: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--json') args.json = true;
    else if (argv[i] === '--write') args.write = true;
    else if (argv[i] === '--check') args.check = true;
    else if (argv[i] === '--tickets') args.tickets = (argv[++i] ?? '').split(',').map((t) => t.trim()).filter(Boolean);
  }
  return args;
}

const lineOf = (source, index) => source.slice(0, index).split('\n').length;
// Checkouts with core.autocrlf=true have CRLF on disk. Work in LF, and write back in the file's own line ending.
const normalise = (text) => text.replaceAll('\r\n', '\n');
const eolOf = (path) => (existsSync(path) && readFileSync(path, 'utf8').includes('\r\n') ? '\r\n' : '\n');
const readNormalised = (path) => (existsSync(path) ? normalise(readFileSync(path, 'utf8')) : null);
const cell = (value) => String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const ticketOf = (id) => (id && !id.startsWith('MAN-') ? id.match(/^([A-Z][A-Z0-9]+-\d+)-\d+$/)?.[1] ?? null : null);
const compareIds = (a, b) => String(a).localeCompare(String(b), 'en', { numeric: true });

// jira.site from the repo-root workflow.toml, for ticket links. A minimal reader: the [jira] table's site = "…".
function jiraSite() {
  const toml = readNormalised(PATHS.workflowToml);
  const section = toml?.match(/^\[jira\]\n([\s\S]*?)(?=^\[|(?![\s\S]))/m)?.[1] ?? '';
  return section.match(/^site\s*=\s*"([^"]+)"/m)?.[1] ?? null;
}

// ─── Parsing ──────────────────────────────────────────────────────────────────

// The /** … */ block immediately above a declaration (only whitespace in between).
function docstringBefore(source, index) {
  const trimmed = source.slice(0, index).trimEnd();
  if (!trimmed.endsWith('*/')) return null;
  const start = trimmed.lastIndexOf('/**');
  if (start === -1) return null;
  const lines = trimmed
    .slice(start + 3, -2)
    .split('\n')
    .map((l) => l.replace(/^\s*\*?\s?/, '').trim())
    .filter(Boolean);
  const summary = lines.find((l) => !/^Verifies:/i.test(l)) ?? '';
  const verifies = lines.find((l) => /^Verifies:/i.test(l))?.replace(/^Verifies:\s*/i, '') ?? null;
  const [head, ref, type, priority] = summary.split('|').map((p) => p.trim());
  const title = head?.replace(ID_PATTERN, '').replace(/^[:\s—-]+/, '').trim() || null;
  return { title, ref: ref || null, type: type || null, priority: priority || null, verifies };
}

function scanSpecs() {
  const tests = [];
  const files = existsSync(TESTS_DIR)
    ? readdirSync(TESTS_DIR, { recursive: true }).map(String).filter((f) => f.endsWith('.spec.ts')).sort().map((f) => join(TESTS_DIR, f))
    : [];

  for (const file of files) {
    const source = normalise(readFileSync(file, 'utf8'));
    for (const match of source.matchAll(DECLARATION_PATTERN)) {
      const [, modifier, , title] = match;
      // Tags may appear in the title or in a { tag: [...] } option on the same declaration.
      // Search for the callback's `async` after the title, so a title containing "async" can't cut the option off.
      const asyncAt = source.indexOf('async', match.index + match[0].length);
      const declaration = source.slice(match.index, asyncAt === -1 ? match.index + 400 : asyncAt);
      tests.push({
        id: title.match(ID_PATTERN)?.[1] ?? null,
        title,
        status: modifier ?? 'active',
        tickets: [...new Set([...declaration.matchAll(TICKET_TAG_PATTERN)].map((m) => m[1]))],
        doc: docstringBefore(source, match.index),
        spec: relative(TESTS_DIR, file).replaceAll('\\', '/'),
        file: relative(SCRIPTS_DIR, file).replaceAll('\\', '/'),
        line: lineOf(source, match.index),
      });
    }
  }
  return tests;
}

// Not-automated cases: "### <ID>: <title>" headings in test-cases.md, with optional **Type**/**Priority**/**Ticket** lines.
function scanTestCasesDoc() {
  const source = readNormalised(PATHS.testCases);
  if (!source) return [];
  const headings = [...source.matchAll(/^### (\S+): (.+)$/gm)].filter((h) => ID_PATTERN.test(h[1]));
  return headings.map((heading, i) => {
    const body = source.slice(heading.index, headings[i + 1]?.index ?? source.length);
    return {
      id: heading[1],
      title: heading[2].trim(),
      ref: body.match(/\*\*Ticket\*\*:\s*([^|\n]+)/)?.[1]?.trim() ?? null,
      type: body.match(/\*\*Type\*\*:\s*([A-Za-z]+)/)?.[1] ?? null,
      priority: body.match(/\*\*Priority\*\*:\s*([A-Za-z]+)/)?.[1] ?? null,
      file: 'qa-output/test-cases.md',
      line: lineOf(source, heading.index),
    };
  });
}

// ─── Checks ───────────────────────────────────────────────────────────────────

function runChecks(tests, manualCases) {
  const errors = [];
  const warnings = [];
  const byId = new Map();
  for (const item of [...tests, ...manualCases]) if (item.id) byId.set(item.id, [...(byId.get(item.id) ?? []), item]);
  for (const [id, list] of byId) {
    if (list.length > 1) errors.push({ check: 'duplicate-id', id, locations: list.map((t) => `${t.file}:${t.line}`) });
  }
  for (const t of tests) {
    const location = `${t.file}:${t.line}`;
    if (!t.id) {
      warnings.push({ check: 'no-recognised-id', title: t.title, location, detail: 'titles start with <TICKET>-<n> or MAN-<slug>-<n>' });
      continue;
    }
    if (!t.doc?.type || !t.doc?.priority) errors.push({ check: 'docstring', id: t.id, location, detail: 'needs /** <ID>: <title> | <ticket> AC<n> | <Type> | <Priority> */ directly above the declaration' });
    if (!t.doc?.verifies) errors.push({ check: 'verifies', id: t.id, location, detail: 'needs a "Verifies:" line in its docstring' });
  }
  return { errors, warnings };
}

// ─── Index rows and derived data ──────────────────────────────────────────────

function buildRows(tests, manualCases) {
  const rows = tests.map((t) => {
    const tickets = [...new Set([ticketOf(t.id), ...t.tickets].filter(Boolean))];
    return {
      id: t.id ?? '—',
      title: t.doc?.title || t.title.replace(ID_PATTERN, '').replace(/^[\s—-]+/, ''),
      ref: [t.doc?.ref, ...tickets.filter((k) => !t.doc?.ref?.includes(k))].filter(Boolean).join(', '),
      type: t.doc?.type ?? '',
      priority: t.doc?.priority ?? '',
      status: t.status,
      verifies: t.doc?.verifies ?? '',
      location: `${t.file}:${t.line}`,
      tickets,
    };
  });
  for (const m of manualCases) {
    const tickets = [ticketOf(m.id)].filter(Boolean);
    rows.push({ id: m.id, title: m.title, ref: m.ref ?? tickets.join(', '), type: m.type ?? '', priority: m.priority ?? '', status: 'manual', verifies: '', location: `${m.file}:${m.line}`, tickets });
  }
  return rows.sort((a, b) => compareIds(a.id, b.id));
}

function summarise(tests, manualCases) {
  const count = (status) => tests.filter((t) => t.status === status).length;
  return {
    declared: tests.length,
    active: count('active'),
    expectedFail: count('fail'),
    skipped: count('skip'),
    fixme: count('fixme'),
    notAutomated: manualCases.length,
    ticketScoped: tests.filter((t) => t.id && !t.id.startsWith('MAN-')).length,
    manualScoped: tests.filter((t) => t.id?.startsWith('MAN-')).length,
  };
}

function ticketMap(rows) {
  const map = {};
  for (const row of rows) for (const ticket of row.tickets) (map[ticket] ??= []).push(row.id);
  return Object.fromEntries(Object.entries(map).sort(([a], [b]) => compareIds(a, b)));
}

// ─── Generated content ────────────────────────────────────────────────────────

function renderIndex(rows, s) {
  return [
    '# Test Index',
    '',
    GENERATED_BANNER,
    '',
    `${s.declared} declared tests (${s.active} active, ${s.expectedFail} expected-fail, ${s.skipped} skipped${s.fixme ? `, ${s.fixme} fixme` : ''}) and ${s.notAutomated} not-automated cases from \`test-cases.md\`.`,
    '',
    '| ID | Title | Ticket / story | Type | Priority | Status | Verifies | Location |',
    '|---|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${cell(r.id)} | ${cell(r.title)} | ${cell(r.ref)} | ${cell(r.type)} | ${cell(r.priority)} | ${STATUS_LABEL[r.status] ?? r.status} | ${cell(r.verifies)} | \`${r.location}\` |`),
    '',
  ].join('\n');
}

function renderJiraMapping(map) {
  const site = jiraSite();
  const link = (ticket) => (site ? `[${ticket}](https://${site}/browse/${ticket})` : ticket);
  const entries = Object.entries(map);
  return [
    '# Jira → Test Mapping',
    '',
    GENERATED_BANNER,
    '',
    'A test belongs to the ticket in its ID (`<TICKET>-<n>`) and to every `@<TICKET>` tag on it.',
    '',
    ...(entries.length
      ? ['| Ticket | Tests | Count |', '|---|---|---|', ...entries.map(([ticket, ids]) => `| ${link(ticket)} | ${ids.join(', ')} | ${ids.length} |`)]
      : ['No tests are linked to a Jira ticket yet.']),
    '',
  ].join('\n');
}

function renderHeaderBlock(s) {
  return [
    `**Tests** (generated by \`npm run qa:ledger -- --write\` — do not edit): ${s.declared} declared = ${s.active} active + ${s.expectedFail} expected-fail + ${s.skipped} skipped${s.fixme ? ` + ${s.fixme} fixme` : ''} · ${s.ticketScoped} ticket-scoped, ${s.manualScoped} MAN-* · ${s.notAutomated} not automated`,
  ];
}

function renderSpecTable(tests) {
  const scripts = JSON.parse(readFileSync(PATHS.packageJson, 'utf8')).scripts ?? {};
  const bySpec = new Map();
  for (const t of tests) bySpec.set(t.spec, [...(bySpec.get(t.spec) ?? []), t]);
  return [
    '| Command | Spec file | Test IDs | Tests |',
    '|---|---|---|---|',
    ...[...bySpec.keys()].sort().map((spec) => {
      const script = Object.entries(scripts).find(([, cmd]) => cmd.trim() === `playwright test tests/${spec}`)?.[0];
      const command = script ? `\`npm run ${script}\`` : `\`npx playwright test tests/${spec}\``;
      const specTests = bySpec.get(spec);
      return `| ${command} | \`${spec}\` | ${specTests.map((t) => t.id).filter(Boolean).sort(compareIds).join(', ')} | ${specTests.length} |`;
    }),
  ];
}

// Replace the lines between <!-- qa-ledger:<name>:start --> and :end -->, keeping any line prefix (e.g. "> ").
function replaceBlock(text, name, contentLines) {
  if (text === null) return null;
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.includes(`<!-- qa-ledger:${name}:start -->`));
  const end = lines.findIndex((l) => l.includes(`<!-- qa-ledger:${name}:end -->`));
  if (start === -1 || end === -1 || end < start) return null;
  const prefix = lines[start].slice(0, lines[start].indexOf('<!--'));
  const body = contentLines.map((l) => (l ? `${prefix}${l}` : prefix.trimEnd()));
  return [...lines.slice(0, start + 1), ...body, ...lines.slice(end)].join('\n');
}

function generatedOutputs(tests, rows, summary, map) {
  const outputs = [
    { path: PATHS.testIndex, content: renderIndex(rows, summary) },
    { path: PATHS.jiraMapping, content: renderJiraMapping(map) },
  ];
  const blocks = [
    { path: PATHS.claudeMd, name: 'header', lines: renderHeaderBlock(summary) },
    { path: PATHS.readme, name: 'spec-table', lines: renderSpecTable(tests) },
  ];
  const problems = [];
  for (const block of blocks) {
    const updated = replaceBlock(readNormalised(block.path), block.name, block.lines);
    if (updated === null) problems.push({ check: 'missing-marker-block', detail: `${relative(QA_ROOT, block.path)} has no qa-ledger:${block.name} markers` });
    else outputs.push({ path: block.path, content: updated });
  }
  return { outputs, problems };
}

// ─── Main ─────────────────────────────────────────────────────────────────────

function main() {
  const args = parseArgs(process.argv.slice(2));
  const tests = scanSpecs();
  const manualCases = scanTestCasesDoc();
  const { errors, warnings } = runChecks(tests, manualCases);
  const rows = buildRows(tests, manualCases);
  const summary = summarise(tests, manualCases);
  const map = ticketMap(rows);
  const { outputs, problems } = generatedOutputs(tests, rows, summary, map);
  errors.push(...problems);
  if (!jiraSite()) warnings.push({ check: 'no-jira-site', detail: 'workflow.toml has no [jira] site — jira-test-mapping.md is written without links' });

  const isStale = (o) => readNormalised(o.path) !== o.content;
  const stale = outputs.filter(isStale).map((o) => relative(QA_ROOT, o.path).replaceAll('\\', '/'));
  const written = [];
  if (args.write) {
    for (const o of outputs.filter(isStale)) {
      writeFileSync(o.path, o.content.replaceAll('\n', eolOf(o.path)));
      written.push(relative(QA_ROOT, o.path).replaceAll('\\', '/'));
    }
  } else if (stale.length) {
    (args.check ? errors : warnings).push({ check: 'generated-stale', detail: `${stale.join(', ')} — run npm run qa:ledger -- --write` });
  }

  const report = {
    summary,
    knownFailures: tests.filter((t) => ['skip', 'fail', 'fixme'].includes(t.status)).map(({ id, status, file, line }) => ({ id, status, location: `${file}:${line}` })),
    tickets: map,
    requestedTickets: args.tickets.length ? Object.fromEntries(args.tickets.map((t) => [t, map[t] ?? []])) : undefined,
    written,
    errors,
    warnings,
  };

  if (args.json) console.log(JSON.stringify(report, null, 2));
  else printSummary(report);
  process.exitCode = errors.length ? 1 : 0;
}

function printSummary({ summary: s, knownFailures, requestedTickets, written, errors, warnings }) {
  console.log('qa-ledger');
  console.log('─────────────────────────────');
  console.log(`Declared tests:     ${s.declared} (${s.active} active, ${s.expectedFail} expected-fail, ${s.skipped} skipped${s.fixme ? `, ${s.fixme} fixme` : ''})`);
  console.log(`ID scheme:          ${s.ticketScoped} ticket-scoped · ${s.manualScoped} MAN-* · ${s.notAutomated} not automated`);
  console.log(`Known failures:     ${knownFailures.length} → ${knownFailures.map((k) => `${k.id ?? '?'} (${k.status})`).join(', ') || 'none'}`);
  if (requestedTickets) {
    console.log('Ticket coverage:');
    for (const [ticket, ids] of Object.entries(requestedTickets)) console.log(`  ${ticket.padEnd(12)} ${ids.length ? ids.join(', ') : '— no coverage'}`);
  }
  if (written.length) console.log(`Written:            ${written.join(', ')}`);
  console.log(`Errors:             ${errors.length}`);
  for (const e of errors) console.log(`  ✗ ${e.check}: ${[e.id, e.locations?.join(', ') ?? e.location, e.detail].filter(Boolean).join(' ')}`);
  console.log(`Warnings:           ${warnings.length}`);
  for (const w of warnings) console.log(`  ! ${w.check}: ${[w.id ?? w.title, w.location && `(${w.location})`, w.detail].filter(Boolean).join(' ')}`);
  console.log('─────────────────────────────');
}

main();
